$$;

create or replace function public.admin_save_settings(p_settings jsonb)
returns void
language plpgsql security definer
set search_path = public, auth
as $$
begin
  if not public.is_site_admin() then raise exception 'Acesso administrativo negado'; end if;
  if jsonb_typeof(p_settings) <> 'object' then raise exception 'Configuração inválida'; end if;
  insert into public.admin_settings(setting_key, setting_value, updated_at, updated_by)
  values ('app', p_settings, now(), auth.uid())
  on conflict (setting_key) do update set setting_value = excluded.setting_value, updated_at = now(), updated_by = auth.uid();
  insert into public.admin_activity_logs(user_id, user_email, event_type, details)
  values (auth.uid(), auth.jwt() ->> 'email', 'admin.settings_updated', jsonb_build_object('setting_key','app'));
end;
$$;

create or replace function public.admin_list_activity(p_limit integer default 100)
returns table(id bigint, user_id uuid, user_email text, event_type text, details jsonb, created_at timestamptz)
language plpgsql security definer
set search_path = public, auth
as $$
begin
  if not public.is_site_admin() then raise exception 'Acesso administrativo negado'; end if;
  return query select l.id, l.user_id, l.user_email, l.event_type, l.details, l.created_at
  from public.admin_activity_logs l order by l.created_at desc limit greatest(1, least(coalesce(p_limit,100),500));
end;
$$;

create or replace function public.admin_log_event(p_event_type text, p_details jsonb default '{}'::jsonb)
returns void
language plpgsql security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null then raise exception 'Autenticação necessária'; end if;
  if length(coalesce(p_event_type,'')) < 1 or length(p_event_type) > 100 then raise exception 'Evento inválido'; end if;
  insert into public.admin_activity_logs(user_id, user_email, event_type, details)
  values (auth.uid(), auth.jwt() ->> 'email', p_event_type, coalesce(p_details,'{}'::jsonb));
end;
$$;

