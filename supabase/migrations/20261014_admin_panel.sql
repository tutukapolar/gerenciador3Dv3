create or replace function public.admin_get_settings()
returns jsonb
language plpgsql security definer
set search_path = public, auth
as $$
declare result jsonb;
begin
  if not public.is_site_admin() then raise exception 'Acesso administrativo negado'; end if;
  select setting_value into result from public.admin_settings where setting_key = 'app';
  return coalesce(result, '{"plans":{"gratuito":{"nome":"Gratuito","preco":0,"max_impressoras":1,"max_filamentos":5,"max_produtos":3,"recursos":["Calculadora básica","Estoque limitado","Dashboard"]},"pro":{"nome":"PRO","preco":19.9,"max_impressoras":-1,"max_filamentos":-1,"max_produtos":-1,"recursos":["Tudo do Gratuito","Impressoras ilimitadas","Precificação para marketplaces","Gerador de anúncios com IA","Recursos avançados"]}}}'::jsonb);
