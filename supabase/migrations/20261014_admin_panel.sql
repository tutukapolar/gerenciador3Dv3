-- Painel administrativo do Negócio 3D.
-- Execute no SQL Editor do projeto Supabase.
-- Acesso administrativo limitado ao e-mail de administrador configurado no app.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  plano text not null default 'gratuito',
  data_expiracao timestamptz,
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists email text;
alter table public.profiles add column if not exists plano text not null default 'gratuito';
alter table public.profiles add column if not exists data_expiracao timestamptz;
alter table public.profiles add column if not exists created_at timestamptz not null default now();

create table if not exists public.admin_settings (
  setting_key text primary key,
  setting_value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

create table if not exists public.admin_activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  user_email text,
  event_type text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
revoke update on table public.profiles from anon, authenticated;
grant select, insert on table public.profiles to authenticated;
alter table public.admin_settings enable row level security;
alter table public.admin_activity_logs enable row level security;

-- Usuário pode ler/editar somente o próprio perfil (não permite promover a si mesmo via policy).
drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles for select to authenticated using (id = auth.uid());
drop policy if exists "profiles_insert_own_free" on public.profiles;
create policy "profiles_insert_own_free" on public.profiles for insert to authenticated with check (id = auth.uid() and coalesce(plano, 'gratuito') = 'gratuito');
drop policy if exists "profiles_update_own" on public.profiles;
-- Não permitir alteração direta do plano pelo próprio usuário. Mudanças administrativas passam pela RPC protegida.

create or replace function public.is_site_admin()
returns boolean
language sql stable security definer
set search_path = public, auth
as $$
  select coalesce(auth.jwt() ->> 'email', '') = 'ytty8229@gmail.com';
$$;

create or replace function public.admin_list_users()
returns table(id uuid, email text, plano text, data_expiracao timestamptz, created_at timestamptz)
language plpgsql security definer
set search_path = public, auth
as $$
begin
  if not public.is_site_admin() then raise exception 'Acesso administrativo negado'; end if;
  return query
    select u.id, u.email::text, coalesce(p.plano, 'gratuito')::text, p.data_expiracao, u.created_at
    from auth.users u left join public.profiles p on p.id = u.id
    order by u.created_at desc;
end;
$$;

create or replace function public.admin_update_user_plan(p_user_id uuid, p_plan text)
returns void
language plpgsql security definer
set search_path = public, auth
as $$
begin
  if not public.is_site_admin() then raise exception 'Acesso administrativo negado'; end if;
  if p_plan not in ('gratuito', 'pro') then raise exception 'Plano inválido'; end if;
  insert into public.profiles (id, email, plano, created_at)
  select u.id, u.email, p_plan, u.created_at from auth.users u where u.id = p_user_id
  on conflict (id) do update set plano = excluded.plano, email = excluded.email;
  if not found then raise exception 'Usuário não encontrado'; end if;
  insert into public.admin_activity_logs (user_id, user_email, event_type, details)
  select auth.uid(), auth.jwt() ->> 'email', 'admin.user_plan_updated', jsonb_build_object('target_user_id', p_user_id, 'new_plan', p_plan);
end;
$$;

